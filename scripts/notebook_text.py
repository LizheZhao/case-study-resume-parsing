SCALABILITY = """\
## Scalability and additional features

What the code already supports, what changes once the volume is real, and what comes next. The reasons behind each choice are in `docs/design.md` (sections 3.4, 6, 7, 9, 10, and 13).

### Other input formats

DOCX and PDF are implemented. For the rest:

| Tier | Formats | Route | Notes |
|---|---|---|---|
| 1 | docx, pdf | python-docx, PyMuPDF | implemented |
| 1 | txt, md, html | read the file directly | a few lines each |
| 2 | doc, rtf, odt, pages | LibreOffice headless to docx or pdf, then tier 1 | adds a system dependency |
| 3 | png, jpg, scanned pdf | vision model, or Tesseract OCR | OCR is cheaper at volume and worse on layout |
| 4 | LinkedIn JSON, ATS XML | map straight into `extracted` | skips the LLM entirely |

### Vision fallback

`extract` decides per file whether the text layer is any good. Under 400 characters on a PDF page, an image covering more than half a page, or more than 10% unknown words after repair, and it switches to vision: pages rendered to PNG at 150 dpi and sent as image blocks with the same schemas. None of the 10 sample files trips it.

### Postgres and pgvector

The DDL in `store/schema.sql` moves to Postgres with three edits. FTS5 becomes a `tsvector` column with a GIN index. The `embeddings` table becomes a `pgvector` column with an HNSW index, which retires the brute-force cosine scan in `VectorIndex`. `parse_jobs` becomes the work queue. SQLite is fine for ten resumes; the vector scan and the single writer are what give out first.

### Queue-based ingest and the `parse_jobs` contract

`ingest()` already treats each file as its own job. A job carries a `file_sha256`, a `prompt_version`, and a status that only moves forward: `queued`, `extracting`, `parsing`, `deriving`, `indexing`, then `ok`, `failed`, or `skipped`. The idempotency key is `(file_sha256, prompt_version)`, so ingesting the same bytes twice under the same prompt is a no-op. Each file is one transaction. A crash leaves you with the old candidate or the new one, never half of each.

Scaling out means swapping the thread pool for a queue (SQS, Cloud Tasks, or a Postgres `SKIP LOCKED` table). Producers insert `queued` rows. Stateless workers claim a row, run extract and parse, write the result. The state machine and the key stay as they are.

Do the arithmetic. 28.4 seconds a resume, 4 workers, call it 8 resumes a minute. 100,000 resumes at that rate is about 8 days. To do it overnight you want around 100 workers and an API rate limit sized for them. Today the only rate limiting is the SDK's own retries (`max_retries=4`); a `RateLimitError` that outlives them is logged as that attempt's error and bumps the ladder to the next rung. A token bucket in front of the client is the piece to add before the 100-worker run.

### Re-parse and re-derive are different operations

A **prompt-version bump** changes what the LLM returns, so every resume has to go through the API again and that costs money. `ingest --force` does it, and a changed `PROMPT_VERSION` makes the skip check miss anyway. A **schema-version bump** only changes how `derived` is computed from `extracted`, so `resume-search rederive` rebuilds derived fields, facet tables, and vectors from the stored `record_json` for free. Keeping the two layers apart is what makes the second case free.

### Term matching beyond the synonym dictionary

Right now skills go through the synonym dictionary in `taxonomy/skills.yaml` with a rapidfuzz fallback, and the cross-check in `parse/verify.py` holds the LLM's skills against that same dictionary. Two more layers are designed:

- **spaCy EntityRuler cross-check.** Phrase patterns compiled from the taxonomy (skills, tools, firms, sectors, certifications, locations, phone prefixes) run over the raw text at ingest. The spans highlight evidence on the Candidate page and give a second, independent read on skills and country. The LLM keeps priority for display; disagreements land in `quality`.
- **Knowledge-graph query expansion.** A networkx graph over the taxonomy YAML (synonym to canonical, skill to category, firm to firm type, approach to related terms) expands a query at search time, so "systematic" also pulls up "stat arb", "factor", and "quant".

### A small classifier as a cheap pre-filter

Sending every resume to an LLM just to learn whether someone is fundamental or systematic is wasteful at volume. A TF-IDF plus logistic-regression classifier trained on the LLM's own `investment_approach` and sector labels handles most of them for close to nothing and sends only the low-confidence ones on. A confusion matrix against the LLM labels sets the threshold. It wants a few hundred labeled resumes, so it belongs to the first bulk load.

### PII

`email`, `phone`, and `location_text` live in their own `candidates` columns and nowhere else. The FTS body is the resume text with email, URL, and phone lines stripped; the embeddings see only the `search_summary` and the experience bullets. A validator rejects any `search_summary` with an `@` or a run of seven or more digits. The full resume text, contact block included, does go to the Anthropic API during parsing. Two things to add before production: strip the contact block before that call, and a read-time redaction switch that masks the three columns by user role.

### Cost per resume at volume

$0.078 a resume measured (10 resumes, $0.7797, at the per-token prices in `ingest/pipeline.py`). Roughly $78 per 1,000 and $7,800 per 100,000 at list prices. Prompt caching is already on for the system prompts. The two remaining levers are the batch API, discounted and a good fit for an overnight bulk load, and the classifier pre-filter above. Judging is extra: $0.65 for a parsing eval, $0.17 for a ranking eval.

### What nondeterminism means for re-ingest

An LLM will not hand you the same JSON twice. The skip check means a re-ingest of the same file under the same prompt version never calls the model, so a stored record stays put. Nondeterminism only gets in when you force a re-parse or bump the prompt version, and the eval harness is the control for exactly that. Run `resume-search eval run --suite parsing` before and after, compare per-field accuracy, and check whether the judge-human agreement moved too. A prompt change that costs a field accuracy or adds a hallucination shows up before it reaches the index.

### Filter semantics

- **The years range is a must filter.** A pasted JD saying "4-8 years" prunes everyone outside it (`years_mode` defaults to `must`). Flip the toggle to `preferred` to score the range instead of cutting on it.
- **Ties sort by name.** Equal final scores come out in candidate-name order.
- **A role with no stated location has no country.** It counts toward neither `current_country` nor `countries_worked`; the contact block and the employer's head office are the fallbacks for `current_country`.
- **`has_cfa` means charterholder.** True for a charterholder or a bare "CFA" entry. A level pass or candidacy sets `cfa_level` instead, and a `CFA` certification criterion matches either through `candidate_certs`.
"""

